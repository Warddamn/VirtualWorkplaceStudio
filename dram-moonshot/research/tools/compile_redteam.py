#!/usr/bin/env python3
"""Compile REDTEAM.md from the physics red team's objections and responses (verbatim, nothing deleted).

Adapted from ram-venture/research/tools/compile_redteam.py. Here "dd" holds a concept slug (e.g. hot-side-memory)
and the personas are DEV (device physics), PROC (process), CIRC (circuits/architecture), IND (industry/cost).

Inputs
  research/redteam/rt_<PERSONA>.json  (optional second round: rt2_<PERSONA>.json)   {"persona": "VET", "persona_name": "...", "objections": [
        {"id": "RT-VET-DD1-01", "dd": "DD1", "severity": "FATAL|MAJOR|MINOR", "section": "...",
         "objection": "...", "would_change_my_mind": "..."}], "overall": {"DD1": "...", ...}}
  research/redteam/responses_<slug>.json {"dd": "DD1", "slug": "...", "title": "...",
        "final_status": "STANDS|DOWNGRADED|KILLED", "status_reason": "...",
        "revised_verdicts": {"possible": "...", "profitable": "...", "doable": "..."},
        "responses": [{"id": "RT-VET-DD1-01", "response": "...",
                       "disposition": "REFUTED|ACCEPTED-MITIGATED|ACCEPTED-DOWNGRADE|ACCEPTED-KILL",
                       "action": "..."}]}
  research/redteam/summary.md (optional narrative inserted at the top)
Output
  REDTEAM.md
Exit code 1 if any objection lacks a response (research/tools/gate_check.py G2 requires zero).
"""
import json
import sys
from pathlib import Path

RV = Path(__file__).resolve().parents[2]
P5 = RV / "research" / "redteam"
OUT = RV / "REDTEAM.md"
SEV_ORDER = {"FATAL": 0, "MAJOR": 1, "MINOR": 2}
DISP = ["REFUTED", "ACCEPTED-MITIGATED", "ACCEPTED-DOWNGRADE", "ACCEPTED-KILL"]


def q(text: str) -> str:
    return "\n".join("> " + ln if ln.strip() else ">" for ln in str(text).strip().splitlines())


def main():
    # Round 1 (rt_*.json) and any round 2 (rt2_*.json) objections; one persona row per persona.
    rounds = 2 if list(P5.glob("rt2_*.json")) else 1
    personas = []
    for f in sorted(P5.glob("rt_*.json")) + sorted(P5.glob("rt2_*.json")):
        d = json.loads(f.read_text(encoding="utf-8"))
        prev = next((p for p in personas if p["persona"] == d["persona"]), None)
        if prev:
            prev["objections"] = prev.get("objections", []) + d.get("objections", [])
            prev.setdefault("overall", {}).update(d.get("overall", {}))
        else:
            personas.append(d)
    resp_files = {}
    for f in sorted(P5.glob("responses_*.json")):
        d = json.loads(f.read_text(encoding="utf-8"))
        resp_files[d["dd"]] = d
    objections = [dict(o, persona=p["persona"], persona_name=p.get("persona_name", p["persona"]))
                  for p in personas for o in p.get("objections", [])]
    ids = [o["id"] for o in objections]
    dup = sorted({i for i in ids if ids.count(i) > 1})
    responses = {}
    for d in resp_files.values():
        for r in d.get("responses", []):
            responses[r["id"]] = r
    missing = [o["id"] for o in objections if o["id"] not in responses]
    orphan = sorted(set(responses) - set(ids))

    dds = sorted({o["dd"] for o in objections} | set(resp_files))
    lines = ["# NEW DRAM — PHYSICS RED TEAM", ""]
    summary = P5 / "summary.md"
    if summary.exists():
        lines += [summary.read_text(encoding="utf-8").strip(), ""]
    lines += ["## Method", "",
              f"{ {3: 'Three', 4: 'Four', 5: 'Five'}.get(len(personas), str(len(personas))) } adversarial reviewers attacked every concept independently, "
              + ("in one round (`rt_*.json`): " if rounds == 1 else "in two rounds (`rt_*.json`, then `rt2_*.json`): ")
              + ", ".join(f"**{p['persona']}** — {p.get('persona_name', '')}" for p in personas) + ". "
              "Every objection is reproduced **verbatim** below with the concept owner's response, a disposition "
              "(REFUTED / ACCEPTED-MITIGATED / ACCEPTED-DOWNGRADE / ACCEPTED-KILL) and the action taken. "
              "Objections are answered, never deleted. This file is generated by `research/tools/compile_redteam.py` "
              "from `research/redteam/rt_*.json` and `research/redteam/responses_*.json`.", "",
              "## Scoreboard", "",
              "| Concept | Final status | Objections | FATAL | MAJOR | MINOR | " + " | ".join(DISP) + " |",
              "|---|---|---|---|---|---|" + "---|" * len(DISP)]
    for dd in dds:
        os_ = [o for o in objections if o["dd"] == dd]
        rd = resp_files.get(dd, {})
        sev = {s: sum(1 for o in os_ if o.get("severity") == s) for s in SEV_ORDER}
        disp = {k: sum(1 for o in os_ if responses.get(o["id"], {}).get("disposition") == k) for k in DISP}
        lines.append(f"| {dd} {rd.get('title', '')} | **{rd.get('final_status', '—')}** | {len(os_)} | "
                     + " | ".join(str(sev[s]) for s in SEV_ORDER) + " | " + " | ".join(str(disp[k]) for k in DISP) + " |")
    lines.append("")
    lines += ["## Reviewers' one-line verdicts", "", "| Reviewer | " + " | ".join(dds) + " |",
              "|---|" + "---|" * len(dds)]
    for p in personas:
        ov = p.get("overall", {})
        lines.append(f"| {p['persona']} | " + " | ".join(str(ov.get(dd, "")).replace("|", "/") for dd in dds) + " |")
    lines.append("")

    for dd in dds:
        rd = resp_files.get(dd, {})
        lines += [f"## {dd} — {rd.get('title', '')} ({rd.get('slug', '')})", "",
                  f"**Final status after red team: {rd.get('final_status', '—')}.** {rd.get('status_reason', '')}", ""]
        rv = rd.get("revised_verdicts")
        if rv:
            lines += [f"*Revised verdicts* — Possible: {rv.get('possible', '')} · Profitable: {rv.get('profitable', '')} · "
                      f"Doable by this founder: {rv.get('doable', '')}", ""]
        os_ = sorted((o for o in objections if o["dd"] == dd),
                     key=lambda o: (SEV_ORDER.get(o.get("severity"), 9), o["persona"], o["id"]))
        for o in os_:
            r = responses.get(o["id"])
            lines += [f"### {o['id']} — {o.get('severity', '')} — {o['persona']} — {o.get('section', '')}", "",
                      q(o.get("objection", "")), ""]
            if o.get("would_change_my_mind"):
                lines += [f"*What would change the reviewer's mind:* {o['would_change_my_mind']}", ""]
            if r:
                lines += [f"**Response — {r.get('disposition', '')}:** {r.get('response', '')}", "",
                          f"*Action taken:* {r.get('action', 'none')}", ""]
            else:
                lines += ["**Response: ⚠ UNANSWERED**", ""]
    if missing or orphan or dup:
        lines += ["## Integrity check", ""]
        lines += [f"- UNANSWERED: {', '.join(missing)}"] if missing else []
        lines += [f"- Responses with no matching objection: {', '.join(orphan)}"] if orphan else []
        lines += [f"- Duplicate objection ids: {', '.join(dup)}"] if dup else []
        lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"REDTEAM.md: {len(objections)} objections, {len(responses)} responses, {len(missing)} unanswered, "
          f"{len(orphan)} orphan responses, {len(dup)} duplicate ids")
    sys.exit(1 if missing else 0)


if __name__ == "__main__":
    main()
