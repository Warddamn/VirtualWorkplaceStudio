#!/usr/bin/env python3
"""Generate SUMMARY_TABLE.md: every surviving concept, one row each, with scores under all three weightings.

Reads research/phase2/concepts_master.json (status, deep_dive, scores) and research/phase5/responses_*.json
(red-team final status per deep dive) and research/phase6/decision.json (PRIMARY/FALLBACK/MOONSHOT) if present.
"""
import json
from pathlib import Path

RV = Path(__file__).resolve().parents[2]
m = json.loads((RV / "research/phase2/concepts_master.json").read_text(encoding="utf-8"))
sel = json.loads((RV / "research/phase3/selection.json").read_text(encoding="utf-8"))
dd_title = {d["dd"]: d["title"] for d in sel["deep_dives"]}
rt = {}
for f in (RV / "research/phase5").glob("responses_*.json"):
    d = json.loads(f.read_text(encoding="utf-8"))
    rt[d["dd"]] = d.get("final_status", "")
dec_path = RV / "research/phase6/decision.json"
dec = json.loads(dec_path.read_text(encoding="utf-8")) if dec_path.exists() else {}
role = {}
for k in ("PRIMARY", "FALLBACK", "MOONSHOT"):
    if dec.get(k, {}).get("dd"):
        role[dec[k]["dd"]] = k

alive = [c for c in m["cards"] if c.get("status") != "KILLED"]
alive.sort(key=lambda c: c.get("rank_default", 999))
killed = [c for c in m["cards"] if c.get("status") == "KILLED"]

lines = ["# SUMMARY TABLE", "",
         f"Every concept that survived the Phase 3 kill pass and scoring: **{len(alive)} of {len(m['cards'])}** "
         f"({len(killed)} killed; reasons in `03_SCORING.md` §2 and `02_CONCEPTS.md`). Scores are consensus "
         "(median of three independent scorers) on a 0–100 scale from `models/scoring.py`; rank of 40 scored concepts "
         "in parentheses. Weightings: **Default** (mission rubric), **Cap** = capital-constrained (×2 capital & "
         "founder-fit), **Moon** = moonshot (×2 moat & margin). Deep-dive status reflects the Phase 5 red team "
         "(`05_REDTEAM.md`). Generated by `research/tools/build_summary_table.py`.", ""]
if role:
    lines += ["**Picks:** " + " · ".join(f"{k}: {dec[k]['dd']} {dd_title.get(dec[k]['dd'], '')}" for k in
                                         ("PRIMARY", "FALLBACK", "MOONSHOT") if k in dec), ""]
lines += ["| ID | Concept | Tier | Default | Cap | Moon | TRL | TTR (mo) | GM mid | Glut? | Deep dive | Red-team status | Role |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
for c in alive:
    dd = c.get("deep_dive", "")
    dd_cell = f"{dd} {dd_title.get(dd, '')}" if dd else "— (not selected)"
    status = rt.get(dd, "") if dd else ""
    r = role.get(dd, "") if dd else ""
    if dd and r and not any(c["id"] == (sel_dd["anchor"]) for sel_dd in sel["deep_dives"] if sel_dd["dd"] == dd):
        r = f"({r} bundle)"
    lines.append(
        f"| {c['id']} | {c['name']} | {c.get('capital_tier', '')} | {c.get('score_default', '')} ({c.get('rank_default', '')}) | "
        f"{c.get('score_capital_constrained', '')} ({c.get('rank_capital_constrained', '')}) | "
        f"{c.get('score_moonshot', '')} ({c.get('rank_moonshot', '')}) | {c.get('trl', '')} | "
        f"{c.get('time_to_first_revenue_months', '')} | {c.get('gross_margin_mid_pct', '')}% | {c.get('survives_glut', '')} | "
        f"{dd_cell} | {status} | {r} |")
lines += ["", "## Kill tally", "",
          "| Stage | Killed |", "|---|---|"]
from collections import Counter
cnt = Counter(c.get("kill_rule", "") for c in killed)
for k, v in sorted(cnt.items(), key=lambda kv: -kv[1]):
    lines.append(f"| {k} | {v} |")
lines.append(f"| **Total** | **{len(killed)}** |")
(RV / "SUMMARY_TABLE.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"SUMMARY_TABLE.md: {len(alive)} surviving concepts, {len(killed)} killed")
